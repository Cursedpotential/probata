_FRONTMATTER_RE = re.compile(r"^---\s*\n(.*?\n)---\s*\n?", re.S)


def parse_frontmatter(text: str) -> tuple[Optional[dict], str]:
    """Very small YAML-frontmatter parser sufficient for this repo's docs:
    flat `key: value` and `key: [a, b]` / `key: []` lines only (matches what
    D-156's own 2026-09-09 docs actually carry, per the design doc's
    frontmatter merge rule). Returns (fields_dict_or_None, body_after_fm)."""
    m = _FRONTMATTER_RE.match(text)
    if not m:
        return None, text
    block = m.group(1)
    fields: dict = {}
    for line in block.splitlines():
        if not line.strip() or line.strip().startswith("#"):
            continue
        if ":" not in line:
            continue
        k, _, v = line.partition(":")
        k = k.strip()
        v = v.strip()
        if v.startswith("[") and v.endswith("]"):
            inner = v[1:-1].strip()
            fields[k] = [x.strip().strip('"\'') for x in inner.split(",") if x.strip()] if inner else []
        else:
            fields[k] = v.strip('"\'')
    return fields, text[m.end():]


def merge_frontmatter(existing: Optional[dict], row: MapRow) -> dict:
    """Merge rule: never drop existing keys; normalize domain -> domains list;
    fill type/domains/status/supersedes/source_path from the mapping row."""
    merged: dict = dict(existing or {})
    if "domain" in merged and "domains" not in merged:
        dv = merged.pop("domain")
        merged["domains"] = dv if isinstance(dv, list) else [dv]
    elif "domain" in merged and "domains" in merged:
        # keep domains; drop the legacy singular key but preserve its value
        dv = merged.pop("domain")
        existing_list = merged["domains"] if isinstance(merged["domains"], list) else [merged["domains"]]
        addl = dv if isinstance(dv, list) else [dv]
        for d in addl:
            if d not in existing_list:
                existing_list.append(d)
        merged["domains"] = existing_list

    merged.setdefault("type", row.doc_type)
    merged.setdefault("domains", list(row.domains))
    merged.setdefault("status", row.status)
    merged.setdefault("supersedes", row.supersedes_path or "")
    merged.setdefault("source_path", row.source_path)
    # type/status/supersedes/source_path are authoritative from the mapping
    # row (the ingest's own ruling), so overwrite rather than trust a stale
    # ad hoc value already in the file — domains is additive-merged above.
    merged["type"] = row.doc_type
    merged["status"] = row.status
    merged["supersedes"] = row.supersedes_path or ""
    merged["source_path"] = row.source_path
    return merged


def render_frontmatter(fields: dict) -> str:
    lines = ["---"]
    # stable, readable key order
    key_order = ["type", "domains", "status", "supersedes", "source_path"]
    seen = set()
    for k in key_order:
        if k in fields:
            seen.add(k)
            lines.append(_render_kv(k, fields[k]))
    for k in sorted(fields.keys()):
        if k in seen:
            continue
        lines.append(_render_kv(k, fields[k]))
    lines.append("---")
    return "\n".join(lines) + "\n"


def _render_kv(k: str, v) -> str:
    if isinstance(v, list):
        inner = ", ".join(v)
        return f"{k}: [{inner}]"
    return f"{k}: {v}"


def apply_frontmatter_and_byline(text: str, row: MapRow, model_name: str, date_str: str) -> tuple[str, bool, bool]:
    """Returns (new_text, had_existing_fm, byline_added)."""
    existing, body = parse_frontmatter(text)
    merged = merge_frontmatter(existing, row)
    fm_block = render_frontmatter(merged)

    byline = f"> _Mirror regenerated: Claude Code · {model_name} · {date_str} (D-156)_"
    body_stripped = body.lstrip("\n")
    byline_added = False
    if byline not in body_stripped[:2000]:
        # Insert under the first H1 title line if present, else at top of body.
        lines = body_stripped.split("\n")
        insert_at = 0
        for i, ln in enumerate(lines):
            if ln.startswith("# "):
                insert_at = i + 1
                break
        # skip existing blank/byline-ish lines right after title to insert cleanly
        lines.insert(insert_at, ("" if insert_at == 0 else "") )
        lines[insert_at] = byline if insert_at == 0 else lines[insert_at]
        if insert_at != 0:
            lines.insert(insert_at, byline)
        else:
            lines[insert_at] = byline
        body_new = "\n".join(lines)
        byline_added = True
    else:
        body_new = body_stripped

    return fm_block + "\n" + body_new, existing is not None, byline_added



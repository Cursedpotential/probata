def git_mv(src: Path, dst: Path) -> None:
    """Move a managed doc, preferring `git mv` so history follows the file.

    Falls back to a plain filesystem move when git refuses. WHY: some managed
    docs are deliberately untracked -- docs/INFRASTRUCTURE.md is gitignored by
    name (.gitignore:95) because it carries credential-shaped lines, and its
    tracked counterpart is INFRASTRUCTURE.template.md. `git mv` on such a file
    exits non-zero, and with check=True that aborted the whole run partway
    through, leaving a half-migrated tree with no rollback. Force-adding it
    instead would put secrets into tracked history, which is the one hard line.
    The fallback relocates the file so links still resolve, and leaves its git
    status exactly as it was.
    """
    dst.parent.mkdir(parents=True, exist_ok=True)
    result = subprocess.run(
        ["git", "mv", "--", str(src), str(dst)],
        cwd=str(REPO_ROOT), capture_output=True, text=True,
    )
    if result.returncode == 0:
        return
    # NEVER overwrite. On Windows the filesystem is case-INSENSITIVE, so a
    # destination can collide with a DIFFERENT row's not-yet-moved source:
    # row 22 moves docs/INDEX.md -> docs/blueprint/INDEX.md while row 197's
    # source is docs/blueprint/index.md -- the same path here. `git mv`
    # refuses that, correctly. A blind shutil.move does not: on 2026-09-09 it
    # clobbered blueprint/index.md ("# Platform Blueprint") with INDEX.md's
    # text, and the next row carried the wrong content onward. Aborting keeps
    # the tree recoverable, which is the whole point of refusing.
    if dst.exists():
        raise RuntimeError(
            f"refusing to move {src} -> {dst}: destination already exists "
            f"(case-insensitive collision with another row's source?). "
            f"git mv said: {result.stderr.strip()}"
        )
    shutil.move(str(src), str(dst))
    print(f"[apply] untracked/ignored, moved without git: {src.relative_to(REPO_ROOT)}")


def cmd_apply(args) -> int:
    csv_path = Path(args.mapping_csv)
    out_dir = Path(args.out_dir)
    rows = load_mapping(csv_path)
    verification = verify_mapping(rows)
    if verification["missing_sources"] or verification["duplicate_mirror_paths"]:
        print("[apply] REFUSING: verification failed (missing sources or duplicate mirror "
              "paths). Re-run --plan and fix the mapping CSV first.", file=sys.stderr)
        return 2

    before_scanned, before_checked, before_dead = compute_dead_links_before()
    before_count = len(before_dead)

    rewrites, _, _, _ = compute_link_rewrites_and_projected_dead(rows)
    rewrite_index: dict[str, list[LinkRewrite]] = {}
    for rw in rewrites:
        rewrite_index.setdefault(rw.file_old, []).append(rw)

    date_str = datetime.date.today().isoformat()
    model_name = args.model or MODEL_BYLINE

    # 1) git mv every moving file
    for r in rows:
        if not r.moves:
            continue
        src = REPO_ROOT / r.source_path
        dst = REPO_ROOT / r.mirror_path
        git_mv(src, dst)

    # 2) rewrite links + inject frontmatter in every managed file at its NEW location
    for r in rows:
        dst = REPO_ROOT / r.mirror_path
        text = read_text(dst)
        for rw in rewrite_index.get(r.source_path, []):
            if rw.target_old in text:
                text = text.replace(f"]({rw.target_old})", f"]({rw.target_new})")
        text, _had_fm, _byline_added = apply_frontmatter_and_byline(text, r, model_name, date_str)
        with open(winlong(dst), "w", encoding="utf-8", newline="\n") as f:
            f.write(text)

    # 3) regenerate INDEX.md
    index_content = generate_index(rows)
    with open(winlong(REPO_ROOT / "docs" / "INDEX.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write(index_content)

    # 4) re-check dead links; refuse (report only, no rollback) if it rose
    after_scanned, after_checked, after_dead = compute_dead_links_before()
    after_count = len(after_dead)

    report = {
        "before_count": before_count,
        "after_count": after_count,
        "delta": after_count - before_count,
    }
    report_path = out_dir / "apply-deadlink-check.json"
    with open(report_path, "w", encoding="utf-8") as f:
        json.dump({
            **report,
            "after_items": [{"file": d.file, "target": d.target, "reason": d.reason} for d in after_dead],
        }, f, indent=2)

    if after_count > before_count:
        print(f"[apply] DEAD LINK COUNT ROSE: {before_count} -> {after_count} "
              f"(+{after_count - before_count}). Files were already moved and modified. "
              f"NOT rolling back automatically — revert via git (git status / git diff / "
              f"git checkout / git mv back as needed). Offending links written to "
              f"{report_path}.", file=sys.stderr)
        for d in after_dead[:40]:
            print(f"    {d.file} -> {d.target}  ({d.reason})", file=sys.stderr)
        return 3

    print(f"[apply] dead-link count: {before_count} -> {after_count} (did not rise). "
          f"Moved {sum(1 for r in rows if r.moves)} files, regenerated docs/INDEX.md.")
    return 0



_LONGPATH_USED: set[str] = set()


def winlong(p: Path) -> str:
    s = str(p.resolve()) if not str(p).startswith("\\\\?\\") else str(p)
    if os.name == "nt" and len(s) >= 240 and not s.startswith("\\\\?\\"):
        _LONGPATH_USED.add(s)
        return "\\\\?\\" + s
    return s


def read_text(p: Path) -> str:
    with open(winlong(p), "r", encoding="utf-8", errors="replace", newline="") as f:
        return f.read()


def file_exists(p: Path) -> bool:
    try:
        return os.path.isfile(winlong(p))
    except OSError:
        return False



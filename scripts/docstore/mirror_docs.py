@dataclass
class MapRow:
    source_path: str  # "docs/..." posix, relative to REPO_ROOT
    doc_type: str
    domains: list[str]
    status: str
    supersedes_path: str
    title: str
    nbytes: int
    sha256: str
    mirror_path: str
    notes: str

    @property
    def moves(self) -> bool:
        return self.source_path != self.mirror_path


def load_mapping(csv_path: Path) -> list[MapRow]:
    rows: list[MapRow] = []
    with open(csv_path, encoding="utf-8", newline="") as f:
        for r in csv.DictReader(f):
            rows.append(
                MapRow(
                    source_path=r["source_path"].replace("\\", "/"),
                    doc_type=r["doc_type"].strip(),
                    domains=[d for d in r["domains"].split("|") if d],
                    status=r["status"].strip(),
                    supersedes_path=(r["supersedes_path"] or "").replace("\\", "/"),
                    title=r["title"],
                    nbytes=int(r["bytes"]) if r["bytes"] else 0,
                    sha256=r["sha256"],
                    mirror_path=r["mirror_path"].replace("\\", "/"),
                    notes=r.get("notes", ""),
                )
            )
    return rows


def verify_mapping(rows: list[MapRow]) -> dict:
    """Every source exists; every mirror_path unique. Returns a report dict;
    does not raise — the caller decides whether missing sources are fatal."""
    missing_sources = []
    for r in rows:
        if not file_exists(REPO_ROOT / r.source_path):
            missing_sources.append(r.source_path)

    seen: dict[str, list[str]] = {}
    for r in rows:
        seen.setdefault(r.mirror_path, []).append(r.source_path)
    dupes = {m: srcs for m, srcs in seen.items() if len(srcs) > 1}

    bad_types = [r.source_path for r in rows if r.doc_type not in RULED_TYPES]
    bad_status = [r.source_path for r in rows if r.status not in RULED_STATUS]

    return {
        "missing_sources": missing_sources,
        "duplicate_mirror_paths": dupes,
        "bad_types": bad_types,
        "bad_status": bad_status,
    }


# ---------------------------------------------------------------------------
# Link scanning — replicates the 2026-09-09 "walk G" / in-place-fixes-gate
# methodology exactly (see docs/reviews/2026-09-09-inplace-fixes-changelog.md
# "GATE — dead-link count"): scan docs/**/*.md excluding docs/private/,
# extract markdown link targets, drop http(s)/mailto/anchor-only/placeholder/
# code-span matches, a leading-/ target is always dead, else test existence
# relative to the linking file's directory.
# ---------------------------------------------------------------------------

_LINK_RE = re.compile(r"(?<!!)\[([^\]]*)\]\(([^)]+)\)")
_CODE_FENCE_RE = re.compile(r"```.*?```", re.S)
_CODE_SPAN_RE = re.compile(r"`[^`\n]*`")
_SCHEME_RE = re.compile(r"^[a-zA-Z][a-zA-Z0-9+.\-]*://")


def _blank_code(text: str) -> str:
    """Replace fenced/inline code spans with equal-length whitespace so link
    regex offsets still line up with the original text, but code-span
    look-alikes (`[x](y)` inside backticks) never match."""
    text = _CODE_FENCE_RE.sub(lambda m: " " * len(m.group(0)), text)
    text = _CODE_SPAN_RE.sub(lambda m: " " * len(m.group(0)), text)
    return text


def scan_md_files(docs_root: Path) -> list[Path]:
    out = []
    for dirpath, dirnames, filenames in os.walk(docs_root):
        dpath = Path(dirpath)
        rel = dpath.relative_to(docs_root).as_posix() if dpath != docs_root else ""
        if rel == "private" or rel.startswith("private/"):
            dirnames[:] = []
            continue
        for fn in filenames:
            if fn.lower().endswith(".md"):
                out.append(dpath / fn)
    return sorted(out)


@dataclass
class LinkRef:
    label: str
    target: str  # raw target string as written
    path_part: str  # target minus #fragment
    fragment: str  # "" or "#..."
    start: int
    end: int


def extract_links(text: str) -> list[LinkRef]:
    clean = _blank_code(text)
    out = []
    for m in _LINK_RE.finditer(clean):
        label, target = m.group(1), m.group(2).strip()
        if not target:
            continue
        path_part, _, frag = target.partition("#")
        out.append(
            LinkRef(
                label=label, target=target, path_part=path_part,
                fragment=("#" + frag) if frag else "", start=m.start(), end=m.end(),
            )
        )
    return out


def classify_link(link: LinkRef) -> str:
    """Returns one of: 'skip-placeholder', 'skip-anchor', 'skip-scheme',
    'skip-mailto', 'dead-absolute', 'check'."""
    t = link.target.strip()
    if t.upper() == "URL":  # the literal "[Title](URL)" placeholder G discarded
        return "skip-placeholder"
    if not link.path_part:
        return "skip-anchor"  # anchor-only, e.g. "#section"
    if t.startswith("mailto:"):
        return "skip-mailto"
    if _SCHEME_RE.match(t):
        return "skip-scheme"  # http(s):// and any other scheme:// link
    if link.path_part.startswith("/"):
        return "dead-absolute"  # G's rule: leading-/ absolute-style is always dead
    return "check"


def resolve_repo_relpath(from_dir: Path, path_part: str) -> Optional[str]:
    """Resolve a relative link target against from_dir; return the repo-root-
    relative POSIX path string, or None if it resolves outside REPO_ROOT."""
    try:
        raw = path_part
        # tolerate %20 etc. — most links in this repo are plain, but be safe
        from urllib.parse import unquote
        raw = unquote(raw)
        combined = (from_dir / raw).resolve()
        rel = combined.relative_to(REPO_ROOT.resolve())
        return rel.as_posix()
    except (ValueError, OSError):
        return None



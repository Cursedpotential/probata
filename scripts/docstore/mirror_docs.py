def generate_index(rows: list[MapRow]) -> str:
    date_str = datetime.date.today().isoformat()
    lines = []
    lines.append("# Documentation Index — Generated View (D-156)")
    lines.append("")
    lines.append(f"> _Mirror regenerated: Claude Code · {MODEL_BYLINE} · {date_str} (D-156)_")
    lines.append(">")
    lines.append(
        "> Generated by `scripts/docstore/mirror_docs.py` from the docstore mapping CSV. "
        "Do not hand-edit — the next `--apply` run overwrites this file. Grouped by type, "
        "then domain, with status and supersession shown per row."
    )
    lines.append("")

    by_type: dict[str, list[MapRow]] = {}
    for r in rows:
        by_type.setdefault(r.doc_type, []).append(r)

    for t in RULED_TYPES:
        trows = by_type.get(t, [])
        if not trows:
            continue
        lines.append(f"## {t} ({len(trows)})")
        lines.append("")
        by_domain: dict[str, list[MapRow]] = {}
        for r in trows:
            key = ",".join(sorted(r.domains)) or "(none)"
            by_domain.setdefault(key, []).append(r)
        for domain_key in sorted(by_domain.keys()):
            drows = sorted(by_domain[domain_key], key=lambda r: r.title.lower())
            lines.append(f"### domain: {domain_key} ({len(drows)})")
            lines.append("")
            lines.append("| Title | Status | Path | Supersedes |")
            lines.append("|---|---|---|---|")
            for r in drows:
                sup = f"[{r.supersedes_path}]({_index_link(r.supersedes_path)})" if r.supersedes_path else ""
                lines.append(
                    f"| {r.title} | {r.status} | [{r.mirror_path}]({_index_link(r.mirror_path)}) | {sup} |"
                )
            lines.append("")

    return "\n".join(lines) + "\n"


def _index_link(mirror_path: str) -> str:
    # INDEX.md lives at docs/INDEX.md; mirror_path is "docs/<type>/<file>"
    if mirror_path.startswith("docs/"):
        return mirror_path[len("docs/"):]
    return mirror_path



def build_argparser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[1] if __doc__ else "")
    mode = p.add_mutually_exclusive_group()
    mode.add_argument("--plan", action="store_true", help="Compute and write the plan (default).")
    mode.add_argument("--apply", action="store_true", help="Execute the plan (git mv, frontmatter, INDEX.md).")
    mode.add_argument("--index-only", action="store_true", help="Regenerate INDEX.md preview only, to scratch.")
    p.add_argument("--mapping-csv", default=str(DEFAULT_MAPPING_CSV))
    p.add_argument("--out-dir", default=str(DEFAULT_OUT_DIR))
    p.add_argument("--scratch-dir", default=str(DEFAULT_SCRATCH_DIR))
    p.add_argument("--model", default=None, help="Model name for the mirror-regenerated byline (apply only).")
    return p


def main(argv: Optional[list[str]] = None) -> int:
    args = build_argparser().parse_args(argv)
    if args.apply:
        return cmd_apply(args)
    if args.index_only:
        return cmd_index_only(args)
    return cmd_plan(args)


if __name__ == "__main__":
    raise SystemExit(main())

def cmd_plan(args) -> int:
    csv_path = Path(args.mapping_csv)
    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    rows = load_mapping(csv_path)
    verification = verify_mapping(rows)

    fatal = bool(verification["missing_sources"]) or bool(verification["duplicate_mirror_paths"])

    move_rows = [r for r in rows if r.moves]
    noop_rows = [r for r in rows if not r.moves]

    per_type: dict[str, int] = {}
    per_status: dict[str, int] = {}
    for r in rows:
        per_type[r.doc_type] = per_type.get(r.doc_type, 0) + 1
        per_status[r.status] = per_status.get(r.status, 0) + 1

    print(f"[plan] mapping CSV: {csv_path} ({len(rows)} rows)")
    print(f"[plan] missing sources: {len(verification['missing_sources'])}")
    print(f"[plan] duplicate mirror_paths: {len(verification['duplicate_mirror_paths'])}")
    print(f"[plan] bad doc_type values: {len(verification['bad_types'])}")
    print(f"[plan] bad status values: {len(verification['bad_status'])}")
    print(f"[plan] moves: {len(move_rows)}  no-op (already at target): {len(noop_rows)}")

    if fatal:
        print("[plan] FATAL verification failures — plan will still be computed for reporting, "
              "but must not be applied until resolved.", file=sys.stderr)

    print("[plan] computing dead-links-before (live tree, walk-G method) ...")
    before_scanned, before_checked, before_dead = compute_dead_links_before()
    print(f"[plan]   scanned {before_scanned} .md files, {before_checked} links checked, "
          f"{len(before_dead)} dead")

    print("[plan] computing link rewrites + projected dead-links-after ...")
    rewrites, after_scanned, after_checked, after_dead = compute_link_rewrites_and_projected_dead(rows)
    print(f"[plan]   scanned {after_scanned} .md files, {after_checked} links checked, "
          f"{len(rewrites)} rewrites, {len(after_dead)} projected dead")

    delta = len(after_dead) - len(before_dead)
    verdict = "OK (did not rise)" if delta <= 0 else "WOULD RISE — DO NOT APPLY AS-IS"
    print(f"[plan] dead-link delta: {delta:+d}  -> {verdict}")

    plan = {
        "generated_at": datetime.datetime.now().isoformat(timespec="seconds"),
        "mapping_csv": str(csv_path),
        "repo_root": str(REPO_ROOT),
        "counts": {
            "total_rows": len(rows),
            "moves": len(move_rows),
            "no_ops": len(noop_rows),
            "per_type": per_type,
            "per_status": per_status,
        },
        "verification": {
            "missing_sources": verification["missing_sources"],
            "duplicate_mirror_paths": verification["duplicate_mirror_paths"],
            "bad_doc_types": verification["bad_types"],
            "bad_status": verification["bad_status"],
            "fatal": fatal,
        },
        "move_list": [{"source_path": r.source_path, "mirror_path": r.mirror_path} for r in move_rows],
        "link_rewrites": [
            {
                "file_old": rw.file_old, "file_new": rw.file_new,
                "target_old": rw.target_old, "target_new": rw.target_new,
                "resolved_target_old": rw.resolved_target_old,
                "resolved_target_new": rw.resolved_target_new,
            }
            for rw in rewrites
        ],
        "dead_links": {
            "before": {
                "scanned_files": before_scanned, "checked_links": before_checked,
                "count": len(before_dead),
                "items": [{"file": d.file, "target": d.target, "reason": d.reason} for d in before_dead],
            },
            "after_projected": {
                "scanned_files": after_scanned, "checked_links": after_checked,
                "count": len(after_dead),
                "items": [{"file": d.file, "target": d.target, "reason": d.reason} for d in after_dead],
            },
            "delta": delta,
            "verdict": verdict,
        },
        "long_paths_used": sorted(_LONGPATH_USED),
    }

    plan_json = out_dir / "mirror-plan.json"
    with open(plan_json, "w", encoding="utf-8") as f:
        json.dump(plan, f, indent=2, ensure_ascii=False)
    print(f"[plan] wrote {plan_json}")

    plan_md = out_dir / "mirror-plan.md"
    with open(plan_md, "w", encoding="utf-8") as f:
        f.write(render_plan_md(plan))
    print(f"[plan] wrote {plan_md}")

    return 1 if fatal else 0



@dataclass
class DeadLinkItem:
    file: str
    target: str
    reason: str


def compute_dead_links_before() -> tuple[int, int, list[DeadLinkItem]]:
    """Replicates walk G / the in-place-fixes gate exactly against the LIVE
    tree. Returns (scanned_file_count, checked_link_count, dead_items)."""
    md_files = scan_md_files(DOCS_ROOT)
    checked = 0
    dead: list[DeadLinkItem] = []
    for f in md_files:
        text = read_text(f)
        for link in extract_links(text):
            klass = classify_link(link)
            if klass.startswith("skip"):
                continue
            checked += 1
            if klass == "dead-absolute":
                dead.append(DeadLinkItem(
                    file=f.relative_to(REPO_ROOT).as_posix(),
                    target=link.target,
                    reason="leading-/ absolute-style target (treated as always dead, per walk G)",
                ))
                continue
            resolved = resolve_repo_relpath(f.parent, link.path_part)
            if resolved is None or not file_exists(REPO_ROOT / resolved):
                dead.append(DeadLinkItem(
                    file=f.relative_to(REPO_ROOT).as_posix(),
                    target=link.target,
                    reason=f"resolved target does not exist on disk: {resolved or '(outside repo)'}",
                ))
    return len(md_files), checked, dead


@dataclass
class LinkRewrite:
    file_old: str
    file_new: str
    target_old: str
    target_new: str
    resolved_target_old: str
    resolved_target_new: str


def compute_link_rewrites_and_projected_dead(
    rows: list[MapRow],
) -> tuple[list[LinkRewrite], int, int, list[DeadLinkItem]]:
    """For every managed markdown file (every CSV row whose source_path ends
    in .md — the mapping also carries a handful of non-.md leave-in-place
    rows that never reach here as containers, matching G's docs/**/*.md
    source scope), compute the rewritten link text and the projected dead-
    link set after the move.

    Scope note: the design doc's §8 step 5 / task framing describes rewrites
    as happening "in every moved file." This implementation computes rewrites
    for EVERY row (moved AND the 7 already-at-mirror-path no-op rows) because
    a no-op container can still hold a link to a target that DOES move —
    restricting rewriting to only the container's own move would leave those
    links silently dead. This is a superset of the literal instruction and
    is documented here rather than applied silently.
    """
    move_map = {r.source_path: r.mirror_path for r in rows}
    by_source = {r.source_path: r for r in rows}

    rewrites: list[LinkRewrite] = []
    dead: list[DeadLinkItem] = []
    checked = 0
    scanned = 0

    # Union of every live docs/**/*.md (private excluded) so files outside the
    # CSV (should be none, but verified rather than assumed) are still walked
    # for the "after" projection — their own location does not change.
    live_md = {p.relative_to(REPO_ROOT).as_posix(): p for p in scan_md_files(DOCS_ROOT)}

    for rel_str, abspath in sorted(live_md.items()):
        scanned += 1
        container_row = by_source.get(rel_str)
        container_new_path = container_row.mirror_path if container_row else rel_str
        container_old_dir = abspath.parent
        container_new_dir = REPO_ROOT / container_new_path
        container_new_dir = container_new_dir.parent

        text = read_text(abspath)
        for link in extract_links(text):
            klass = classify_link(link)
            if klass in ("skip-placeholder", "skip-anchor", "skip-scheme", "skip-mailto"):
                continue
            if klass == "dead-absolute":
                checked += 1
                dead.append(DeadLinkItem(
                    file=container_new_path, target=link.target,
                    reason="leading-/ absolute-style target (always dead, per walk G; unaffected by moves)",
                ))
                continue

            checked += 1
            resolved_old = resolve_repo_relpath(container_old_dir, link.path_part)

            if resolved_old is not None and (
                resolved_old.startswith("docs/private/") or resolved_old == "docs/private"
            ):
                # untouched per task spec; existence unaffected by the move
                if not file_exists(REPO_ROOT / resolved_old):
                    dead.append(DeadLinkItem(
                        file=container_new_path, target=link.target,
                        reason=f"docs/private/** target left untouched and does not exist: {resolved_old}",
                    ))
                continue

            if resolved_old is None:
                dead.append(DeadLinkItem(
                    file=container_new_path, target=link.target,
                    reason="link target resolves outside the repository root",
                ))
                continue

            target_row = by_source.get(resolved_old)
            if target_row is not None and target_row.moves:
                # Target is a managed document that is moving — rewrite.
                new_target_abs = REPO_ROOT / target_row.mirror_path
                new_rel = os.path.relpath(new_target_abs, start=container_new_dir)
                new_rel_posix = Path(new_rel).as_posix()
                new_target_str = new_rel_posix + link.fragment
                if container_row is None or not container_row.moves:
                    # container path unchanged, but target moved: still a rewrite
                    pass
                if new_target_str != link.target:
                    rewrites.append(LinkRewrite(
                        file_old=rel_str,
                        file_new=container_new_path,
                        target_old=link.target,
                        target_new=new_target_str,
                        resolved_target_old=resolved_old,
                        resolved_target_new=target_row.mirror_path,
                    ))
                # post-move it exists by construction (source verified to exist)
                continue

            if container_row is not None and container_row.moves and target_row is None:
                # container moves but target is unmanaged (asset/script/etc.)
                # and did not move — link text must still be recomputed even
                # though the target's location is unchanged, because the
                # container's directory changed.
                old_target_abs = REPO_ROOT / resolved_old
                new_rel = os.path.relpath(old_target_abs, start=container_new_dir)
                new_rel_posix = Path(new_rel).as_posix()
                new_target_str = new_rel_posix + link.fragment
                if file_exists(old_target_abs):
                    if new_target_str != link.target:
                        rewrites.append(LinkRewrite(
                            file_old=rel_str, file_new=container_new_path,
                            target_old=link.target, target_new=new_target_str,
                            resolved_target_old=resolved_old, resolved_target_new=resolved_old,
                        ))
                    continue
                else:
                    dead.append(DeadLinkItem(
                        file=container_new_path, target=link.target,
                        reason=f"unmanaged target does not exist on disk: {resolved_old}",
                    ))
                    continue

            # Neither container nor target moves for this link — text stays
            # identical; dead-ness is whatever it is today.
            if not file_exists(REPO_ROOT / resolved_old):
                dead.append(DeadLinkItem(
                    file=container_new_path, target=link.target,
                    reason=f"resolved target does not exist on disk (unaffected by move): {resolved_old}",
                ))

    return rewrites, scanned, checked, dead


